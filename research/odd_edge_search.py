"""Exact search for primitive perfect cuboids with bounded odd edge.
No artificial bound on even edges. For odd a, (d-b)(d+b)=a^2,
so every b is generated by a positive divisor u<a of a^2.
"""
from math import isqrt,gcd
import json,sys

def scan(limit):
    spf=list(range(limit+1))
    for p in range(3,isqrt(limit)+1,2):
        if spf[p]==p:
            for x in range(p*p,limit+1,2*p):
                if spf[x]==x: spf[x]=p
    def divisors_squared(a):
        n=a; ds=[1]
        while n>1:
            p=spf[n]; e=0
            while n%p==0: n//=p; e+=1
            ds=[d*p**k for d in ds for k in range(2*e+1)]
        return ds
    out={'odd_edge_limit':limit,'odd_edges_tested':0,'candidate_even_edge_pairs':0,'primitive_euler_bricks':0,'perfect_cuboids':[]}
    for a in range(1,limit+1,2):
        out['odd_edges_tested']+=1
        aa=a*a
        bs=sorted((aa//u-u)//2 for u in divisors_squared(a) if u<a)
        for i,b in enumerate(bs):
            for c in bs[i+1:]:
                if gcd(gcd(a,b),c)!=1: continue
                out['candidate_even_edge_pairs']+=1
                n=b*b+c*c
                if isqrt(n)**2!=n: continue
                out['primitive_euler_bricks']+=1
                if isqrt(n+aa)**2==n+aa: out['perfect_cuboids'].append([a,b,c])
    return out
if __name__=='__main__':
    print(json.dumps(scan(int(sys.argv[1]) if len(sys.argv)>1 else 100000),indent=2))
